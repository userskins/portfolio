"""Rebuild the checked-in original word banks. Dev only: pip install wordfreq pymorphy3.

No dictionary, API, font or package is requested by the game at runtime.
Wordfreq supplies frequency ordering; pymorphy3 verifies Russian parts of speech.
"""
import sys, re, json, random
from pathlib import Path
import wordfreq, pymorphy3

ROOT = Path(__file__).resolve().parents[1]
morph = pymorphy3.MorphAnalyzer()
rng = random.Random(291126)
seed = (ROOT / 'scripts/kroko-content-seeds.txt').read_text()
people, films = seed.split('[entities]\n')[1].split('[rare]')[0].split('Титаник\n', 1)
people = people.strip().splitlines()
films = ['Титаник'] + films.strip().splitlines()
films = [f for f in films if f not in {'Отель Трансильвания', 'Солнце пустыни', 'Любовь и пижоны', 'Реквием', 'Курочка Ряба'}]
def norm(s): return s.lower().replace('ё', 'е').strip()
def unique(xs): return list(dict.fromkeys(xs))
people = unique(people); films = unique(films)
# Every mode gets both people and films, with a broad mix of decades.
entities = rng.sample(people, 225) + rng.sample(films, 225)
rng.shuffle(entities)
reserved = set(map(norm, entities))
rare = []
for w in seed.split('[rare]\n')[1].lower().split():
    if not re.fullmatch('[а-яё-]+', w) or norm(w) in reserved: continue
    p = morph.parse(w)[0]
    if not p.is_known or p.tag.POS not in ('NOUN', 'ADJF'): continue
    w = p.normal_form
    if norm(w) not in reserved:
        rare.append(w); reserved.add(norm(w))
assert len(rare) >= 450, len(rare)
rare.sort(key=lambda w:wordfreq.zipf_frequency(w,'ru')); rare = rare[:450]; rng.shuffle(rare)

# Reject vulgar/derogatory vocabulary and words which make poor party prompts.
blocked = re.compile(r'хуй|хуё|хуе|пизд|бляд|блят|ебать|ёб|ебан|ебнут|говн|дерьм|залуп|мудак|мудил|дебил|кретин|идиот|проститу|порн|эрот|изнасил|суицид|самоубий|гомосекс|педоф|нацист|фашист|расист|негр|жид|сперм|пенис|вагин|пидор|пидар|шлюх|сис[ьк]|срать|ссать|мочить|убивать|убить|убий|умирать|умереть|казнить|смерт|пытать|пытка|расстрел|террор|инвалид|даун|слабоум|болезн|раковый|онколог|дьявол|сатан|божеств|божий|господний|еврей|русский|российский|украин|американ|советский|немец|английский|французский|китайский|европейский')
groups = { 'INFN': [], 'NOUN': [], 'ADJF': [] }
needs = {'INFN':900, 'NOUN':1350, 'ADJF':900}
for raw in wordfreq.top_n_list('ru', 250000):
    if not re.fullmatch('[а-яё]{4,21}',raw) or blocked.search(raw): continue
    p = morph.parse(raw)[0]
    if not p.is_known or p.tag.POS not in groups: continue
    pos = p.tag.POS; w = p.normal_form
    if len(groups[pos]) >= needs[pos] or norm(w) in reserved or blocked.search(w): continue
    if set(p.tag.grammemes) & {'Name','Surn','Patr','Geox','Orgn','Trad','Abbr','Apro','Anum','Poss'}: continue
    if pos == 'NOUN' and (w.endswith(('ое','ее')) or wordfreq.zipf_frequency(w,'ru')<3.0): continue
    if pos == 'NOUN' and w.endswith(('ние','ство','ость','изм','ция','знь','зис')) and w not in {'растение','здание','печенье','варенье','украшение','ожерелье'}: continue
    if pos == 'NOUN' and (p.tag.animacy == 'anim' and p.tag.gender is None): continue
    if pos == 'ADJF' and (w.endswith(('ский','цкий','вший','ющий','ящий')) or wordfreq.zipf_frequency(w,'ru')<2.8): continue
    if pos == 'ADJF' and (len(w)<5 or not w.endswith(('ый','ий','ой'))): continue
    if pos == 'INFN' and not w.endswith(('ть','ться','ти','тись','чь','чься')): continue
    groups[pos].append(w); reserved.add(norm(w))
    if all(len(groups[k]) == needs[k] for k in needs): break
assert {k:len(v) for k,v in groups.items()} == needs, {k:len(v) for k,v in groups.items()}

# Interleave frequency ranks before shuffling to give each mode a similar range.
banks = {m:{} for m in ('show','explain','draw')}
sources = [(1, groups['INFN'],2), (2,groups['NOUN'],3), (3,rare,1), (4,entities,1), (5,groups['ADJF'],2)]
for number, words, size in sources:
    for i, mode in enumerate(banks):
        pool=words[i::3]; rng.shuffle(pool)
        assert len(pool)==150*size, (mode,number,len(pool))
        banks[mode][number]=[' | '.join(pool[j:j+size]) for j in range(0,len(pool),size)]

out='// Original КРОКО word banks. Generated by scripts/build-kroko-content.py.\n// 150 prompts per mode and number. No individual target belongs to two modes.\nexport const BANKS = {\n'
for mode,buckets in banks.items():
    out+=json.dumps(mode)+':{\n'
    for n,lines in buckets.items():
        out+=f'{n}:`'+ '\n'.join(lines)+'`,\n'
    out+='},\n'
out+='};\n'
(ROOT/'client/studio/public/kroko/cards-data.js').write_text(out)
print('Built 2250 cards / 4050 distinct target entries; '+str(len(out.encode()))+' bytes.')
for mode,buckets in banks.items():
    print(mode, {n:len(lines) for n,lines in buckets.items()})
    print({n:lines[:3] for n,lines in buckets.items()})
