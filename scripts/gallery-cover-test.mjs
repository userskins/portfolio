import assert from 'node:assert/strict';
import fs from 'node:fs/promises';

const { chromium } = await import(process.env.STUDIO_PLAYWRIGHT || '/tmp/studio-tools/node_modules/playwright/index.mjs');
await fs.mkdir('gallery-cover-review',{recursive:true});
const browser = await chromium.launch({headless:true});
const page = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:4173/studio/',{waitUntil:'networkidle',timeout:45000});
await page.evaluate(()=>document.fonts.ready);
const preview=page.getByTestId('gallery-desk-cover');
const current=()=>preview.getAttribute('data-gallery-image-id');
assert.equal(await preview.count(),1,'gallery shows one framed picture, not a separate slider');
assert.equal(await page.locator('.print-stack .laptop-next,.print-stack [data-testid^="gallery-next"],.print-stack [data-testid^="gallery-prev"]').count(),0,'no gallery carousel controls');
const initial=await current();
assert.ok(Number(initial)>=1 && Number(initial)<=81,'initial gallery picture is one of the actual works');
await page.screenshot({path:'gallery-cover-review/01-initial-mobile.png',fullPage:true});
await page.waitForFunction(previous=>document.querySelector('[data-testid="gallery-desk-cover"]')?.getAttribute('data-gallery-image-id')!==previous,initial,{timeout:8500});
const next=await current();
assert.notEqual(next,initial,'gallery picture changes automatically without a slider');
await page.locator('[data-testid="open-gallery"]').click();
await page.locator('.reader[role="dialog"]').waitFor();
assert.equal(await page.locator('.gallery-wall button').count(),78,'random desk preview does not change the real gallery');
await page.locator('.reader .back-to-desk').click();
await page.locator('.reader[role="dialog"]').waitFor({state:'detached',timeout:7000});
assert.deepEqual(errors,[],'no runtime errors');
await fs.writeFile('gallery-cover-review/results.json',JSON.stringify({passed:true,checks:['random gallery picture','automatic non-repeating change','no controls','real gallery intact','no errors'],initial,next},null,2));
await browser.close();
console.log('Random auto-changing gallery cover and original gallery checks passed.');
